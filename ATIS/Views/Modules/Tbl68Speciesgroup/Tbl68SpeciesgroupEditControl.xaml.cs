    // ---------------------------------------------------------                   
    // VALDATINHELPER
    // ---------------------------------------------------------                   

    private void UpdateValidationState(TextBox box, bool hasError)
    {
        if (box == null)
            return;

        if (hasError)
        {
            VisualStateManager.GoToState(box, "Invalid", true);
            return;
        }

        if (box.FocusState == FocusState.Pointer || box.FocusState == FocusState.Keyboard)
            VisualStateManager.GoToState(box, "Focused", true);
        else
            VisualStateManager.GoToState(box, "Normal", true);
    }

    // ---------------------------------------------------------                   
    // SPECIESGROUPNAME VALIDATION
    // ---------------------------------------------------------                   
    private void SpeciesgroupNameBox_OnTextChanged(object sender, TextChangedEventArgs e)
    {
        UpdateValidationState(SpeciesgroupNameBox, Item?.HasSpeciesgroupNameError ?? false);
